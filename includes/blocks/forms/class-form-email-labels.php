<?php
/**
 * Field labels for the {all_fields} summary in notification emails.
 *
 * @package DesignSetGo
 * @since 2.11.2
 */

namespace DesignSetGo\Blocks;

defined( 'ABSPATH' ) || exit;

/**
 * Form_Email_Labels.
 *
 * The recipient of a notification never saw the form's markup, so a field is
 * named by what the visitor saw, never by its `name` attribute. In order:
 *
 * 1. The field's label as rendered on the page (placeholder when the label is
 *    empty — see Form_Handler::extract_field_labels_from_blocks()). Labels are
 *    taken verbatim, so a form authored or translated into another language
 *    reports in that language.
 * 2. A hand-written field name, title-cased (`job_title` → "Job Title").
 * 3. "Hidden field" / "Untitled field" when the name was generated by the
 *    editor (`field_ecbc26c5`, `select-662eef03`): those ids mean nothing to
 *    the recipient.
 *
 * A label already used by an earlier field gets " (2)", " (3)", … so two
 * "Name" fields stay distinguishable without exposing their ids.
 */
class Form_Email_Labels {

	/**
	 * Names the editor generates for a new field: a prefix plus the first 8
	 * hex characters of the block's clientId (see each form-*-field edit.js).
	 * The phone field adds a `_country_code` companion.
	 */
	const GENERATED_NAME = '/^(?:field_|(?:checkbox|date|hidden|number|phone|select|time|url)-)[0-9a-f]{8}(?:_country_code)?$/i';

	/**
	 * Resolve a display label for every submitted field, in submission order.
	 *
	 * @param array                 $fields Sanitized fields keyed by name, each { value, type }.
	 * @param array<string, string> $labels Visible labels keyed by field name.
	 * @return array<string, string> Display labels keyed by field name.
	 */
	public static function resolve( array $fields, array $labels ): array {
		$resolved = array();
		$seen     = array();

		foreach ( $fields as $name => $data ) {
			$name  = (string) $name;
			$label = isset( $labels[ $name ] ) ? trim( (string) $labels[ $name ] ) : '';

			if ( '' === $label ) {
				$type  = is_array( $data ) && isset( $data['type'] ) ? (string) $data['type'] : '';
				$label = self::fallback( $name, $type );
			}

			$key          = function_exists( 'mb_strtolower' ) ? mb_strtolower( $label, 'UTF-8' ) : strtolower( $label );
			$seen[ $key ] = isset( $seen[ $key ] ) ? $seen[ $key ] + 1 : 1;

			if ( $seen[ $key ] > 1 ) {
				/* translators: 1: field label, 2: occurrence number of that label in the form */
				$label = sprintf( __( '%1$s (%2$d)', 'designsetgo' ), $label, $seen[ $key ] );
			}

			$resolved[ $name ] = $label;
		}

		return $resolved;
	}

	/**
	 * Label for a field with no visible label.
	 *
	 * @param string $name Field name.
	 * @param string $type Server-side field type.
	 * @return string Readable label.
	 */
	private static function fallback( $name, $type ) {
		if ( '' !== $name && ! preg_match( self::GENERATED_NAME, $name ) ) {
			return ucwords( str_replace( array( '_', '-' ), ' ', $name ) );
		}

		return 'hidden' === $type
			? __( 'Hidden field', 'designsetgo' )
			: __( 'Untitled field', 'designsetgo' );
	}
}
