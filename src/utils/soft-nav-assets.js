/**
 * Load the assets that content swapped in without a page load needs.
 *
 * A soft navigation (Airo's frontend refresh, a Query "load more") replaces
 * page content but runs none of the new content's <script> tags, so a block
 * or extension the first page didn't use would arrive with no script. PHP
 * prints `window.dsgoAssets` (includes/core/class-frontend-asset-manifest.php):
 * every DesignSetGo block and extension bundle that isn't on the page yet,
 * what marks it in the DOM, and the scripts (with dependencies and inline
 * data) and styles it needs. After each `dsgo-content-loaded`, this loads what
 * the DOM now needs, then re-dispatches the event so the new scripts
 * initialize (most only listen for DOMContentLoaded and that event).
 *
 * @package
 */

const SOURCE = 'dsgo-bundles';

/**
 * In-flight or finished script loads, by handle. Resolves to whether the
 * script (and its dependencies) ran.
 *
 * @type {Map<string, Promise<boolean>>}
 */
const scriptLoads = new Map();

/**
 * Run inline code the way WordPress prints it, as its own <script>.
 *
 * @param {string} id   Element ID, e.g. `<handle>-js-before`.
 * @param {string} code JavaScript source generated by PHP.
 */
function runInline(id, code) {
	if (!code || document.getElementById(id)) {
		return;
	}
	const script = document.createElement('script');
	script.id = id;
	script.textContent = code;
	document.body.appendChild(script);
}

/**
 * Whether a stylesheet is already on the page: printed as a link, inlined
 * by WordPress, or inlined by DesignSetGo's critical CSS.
 *
 * @param {string} handle Style handle.
 * @return {boolean} True when present.
 */
function hasStyle(handle) {
	return Boolean(
		document.getElementById(`${handle}-css`) ||
			document.getElementById(`${handle}-inline-css`) ||
			document.querySelector(`[data-dsgo-handles~="${handle}"]`)
	);
}

/**
 * Append a stylesheet and its inline additions.
 *
 * @param {string} handle Style handle.
 * @param {Object} style  Manifest entry: { href, after? }.
 */
function loadStyle(handle, style) {
	if (!style?.href || hasStyle(handle)) {
		return;
	}
	const link = document.createElement('link');
	link.id = `${handle}-css`;
	link.rel = 'stylesheet';
	link.href = style.href;
	document.head.appendChild(link);

	if (style.after) {
		const inline = document.createElement('style');
		inline.id = `${handle}-inline-css`;
		inline.textContent = style.after;
		document.head.appendChild(inline);
	}
}

/**
 * Load a script after its dependencies, with its inline data around it.
 *
 * @param {string} handle  Script handle.
 * @param {Object} scripts Manifest scripts, by handle.
 * @return {Promise<boolean>} Whether the script is now on the page.
 */
function loadScript(handle, scripts) {
	if (scriptLoads.has(handle)) {
		return scriptLoads.get(handle);
	}
	if (document.getElementById(`${handle}-js`)) {
		return Promise.resolve(true);
	}

	const entry = scripts[handle];
	if (!entry) {
		// Not on the page and not loadable: anything needing it must wait
		// for a full page load.
		return Promise.resolve(false);
	}

	const loading = Promise.all(
		(entry.deps || []).map((dep) => loadScript(dep, scripts))
	).then((results) => {
		if (results.includes(false)) {
			return false;
		}

		runInline(`${handle}-js-before`, entry.before);

		// An alias handle only groups its dependencies.
		if (!entry.src) {
			return true;
		}

		return new Promise((resolve) => {
			const script = document.createElement('script');
			script.id = `${handle}-js`;
			script.src = entry.src;
			script.onload = () => {
				runInline(`${handle}-js-after`, entry.after);
				resolve(true);
			};
			// One failed script must not block the others.
			script.onerror = () => resolve(false);
			document.body.appendChild(script);
		});
	});

	scriptLoads.set(handle, loading);
	return loading;
}

/**
 * Whether the current DOM contains a trigger's block or extension.
 *
 * @param {Object}      trigger Manifest trigger: { needles } or { selector }.
 * @param {Function}    getHtml Lazily serialized body HTML.
 * @param {HTMLElement} root    Document to query.
 * @return {boolean} True when present.
 */
function matches(trigger, getHtml, root) {
	if (trigger.selector) {
		try {
			return root.querySelector(trigger.selector) !== null;
		} catch (e) {
			return false;
		}
	}
	// Extension bundles use the same literal-substring test PHP runs.
	const needles = Array.isArray(trigger.needles) ? trigger.needles : [];
	return needles.some((needle) => getHtml().includes(needle));
}

/**
 * Load every asset the current DOM needs but the page doesn't have.
 *
 * @return {Promise<void>} Settles once loaded scripts have been announced.
 */
export function loadMissingAssets() {
	const manifest = window.dsgoAssets;
	if (!manifest || !Array.isArray(manifest.triggers) || !document.body) {
		return Promise.resolve();
	}

	let html = null;
	const getHtml = () => {
		if (html === null) {
			html = document.body.innerHTML;
		}
		return html;
	};

	const scripts = manifest.scripts || {};
	const styles = manifest.styles || {};
	const pending = [];

	manifest.triggers.forEach((trigger) => {
		if (!matches(trigger, getHtml, document)) {
			return;
		}
		(trigger.styles || []).forEach((handle) =>
			loadStyle(handle, styles[handle])
		);
		(trigger.scripts || []).forEach((handle) => {
			if (!document.getElementById(`${handle}-js`)) {
				pending.push(loadScript(handle, scripts));
			}
		});
	});

	if (pending.length === 0) {
		return Promise.resolve();
	}

	return Promise.all(pending).then((results) => {
		if (results.includes(true)) {
			document.dispatchEvent(
				new CustomEvent('dsgo-content-loaded', {
					detail: { source: SOURCE },
				})
			);
		}
	});
}

document.addEventListener('dsgo-content-loaded', (event) => {
	// Our own re-dispatch, or a bfcache restore of an unchanged page.
	const source = event.detail?.source;
	if (source === SOURCE || source === 'bfcache') {
		return;
	}
	loadMissingAssets();
});
